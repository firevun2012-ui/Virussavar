    def update_text_width(self, instance, value):
        self.log_area.text_size = (instance.width, None)
        self.log_area.height = instance.texture_size[1]

    def guvenli_log_yaz(self, metin):
        Clock.schedule_once(lambda dt: setattr(self.log_area, 'text', self.log_area.text + metin))

    def yara_ile_tara(self, dosya_yolu):
        if not self.rules: return "YARA Aktif Değil"
        try:
            if os.path.isdir(dosya_yolu):
                return "KLASÖR 📁"
            
            matches = self.rules.match(dosya_yolu)
            if matches: return f"🚨 TEHDİT BULUNDU: {matches[0].rule}"
            return "TEMİZ ✅"
        except Exception as e:
            return "Okuma İzni Yok ❌"

    def dosya_secici_ac(self, instance):
        ana_dizin = "/storage/emulated/0" if os.path.exists("/storage/emulated/0") else "."
        icerik = BoxLayout(orientation='vertical', spacing=10)
        
        self.dosya_gezgini = FileChooserListView(
            path=ana_dizin, 
            dirselect=True, 
            multiselect=False
        )
        
        self.dosya_gezgini.selection_color = [0.31, 0.98, 0.48, 0.8] 
        icerik.add_widget(self.dosya_gezgini)

        self.secim_takip = Label(text="Seçilen: Yok", size_hint_y=None, height=30, color=(0.31, 0.98, 0.48, 1), bold=True)
        icerik.add_widget(self.secim_takip)
        self.dosya_gezgini.bind(selection=self.secim_degisti)

        buton_tara = Button(
            text="SEÇİLENİ TARA VE ANALİZ ET 🛡️", 
            size_hint_y=None, 
            height=60, 
            font_size='16sp',
            bold=True,
            background_normal='',
            background_color=(0.31, 0.98, 0.48, 1), 
            color=(0.1, 0.1, 0.14, 1)
        )
        icerik.add_widget(buton_tara)

        self._popup = Popup(title="Tek Tık: Seç (Yeşil Olur) / Çift Tık: Klasör İçine Gir", content=icerik, size_hint=(0.95, 0.95))
        buton_tara.bind(on_press=self.dosya_secildi_sonuc)
        self._popup.open()

    def secim_degisti(self, instance, value):
        if value:
            self.secim_takip.text = f"Seçilen: {os.path.basename(value[0])}"

    def dosya_secildi_sonuc(self, instance):
        secim = self.dosya_gezgini.selection
        self._popup.dismiss()
        
        if not secim:
            self.guvenli_log_yaz(">> Seçim yapılmadı.\n")
            return
        
        dosya_yolu = secim[0]
        
        if os.path.isdir(dosya_yolu):
            self.log_area.text = f">> 📁 Seçilen Klasör Taranıyor:\n>> {dosya_yolu}\n\n"
            threading.Thread(target=self.ozel_klasor_tarama, args=(dosya_yolu,)).start()
            return

        self.log_area.text = f">> 📄 Tekli Dosya Analiz Ediliyor...\n>> {dosya_yolu}\n\n"
        sonuc = self.yara_ile_tara(dosya_yolu)
        self.guvenli_log_yaz(f"[SONUÇ] -> {os.path.basename(dosya_yolu)}: {sonuc}\n")
        
        if "🚨" in sonuc:
            self.status_box.text = "TEHLİKE TESPİT EDİLDİ!"
            self.status_box.color = (1, 0.3, 0.3, 1)
        else:
            self.status_box.text = "SİSTEM GÜVENLİ"
            self.status_box.color = (0.31, 0.98, 0.48, 1)

    def ozel_klasor_tarama(self, klasor_yolu):
        toplam = 0
        virus = 0
        for kok, _, dosyalar in os.walk(klasor_yolu):
            for d in dosyalar:
                yol = os.path.join(kok, d)
                toplam += 1
                sonuc = self.yara_ile_tara(yol)
                if "🚨" in sonuc:
                    virus += 1
                    self.guvenli_log_yaz(f"[!] {d} -> ZARARLI BULUNDU!\n")
        
        self.guvenli_log_yaz(f"\n>> 📊 TARAMA BİTTİ\n>> Klasördeki Dosya: {toplam} | Tehdit: {virus}\n")

    def genel_tarama_tetikle(self, instance):
        self.log_area.text = ">> 🔄 TÜM DOWNLOAD KLASÖRÜ TARANIYOR...\n"
        threading.Thread(target=self.arka_plan_genel_tarama).start()

    def arka_plan_genel_tarama(self):
        hedef = "/storage/emulated/0/Download"
        if not os.path.exists(hedef): hedef = "."
        self.ozel_klasor_tarama(hedef)

